import { useState } from "react";

import { EVENT_ICONS, EVENT_TONES, formatTime } from "../components/EventLog";
import MessagesPanel from "../components/MessagesPanel";
import type { EventType, SimulationState } from "../api/types";

type Filter = EventType | "all";

const FILTERS: Filter[] = ["all", "system", "election", "replication", "crash", "recovery", "partition"];

interface Props {
  state: SimulationState;
}

export default function Timeline({ state }: Props) {
  const [filter, setFilter] = useState<Filter>("all");

  const events = [...state.recent_events].reverse(); // newest first
  const visible = filter === "all" ? events : events.filter((e) => e.type === filter);

  return (
    <div className="mx-auto max-w-4xl px-4 py-6 sm:px-6 lg:px-8">
      <div className="mb-5">
        <h2 className="text-lg font-semibold text-slate-200">Event Timeline</h2>
        <p className="mt-1 text-sm text-slate-400">
          Every event below was generated by the simulation engine. Run a
          scenario or use the simulator controls to create new ones.
        </p>
      </div>

      {/* Frontend-only filter */}
      <div className="flex flex-wrap gap-2" role="group" aria-label="Filter events by type">
        {FILTERS.map((type) => {
          const count = type === "all" ? events.length : events.filter((e) => e.type === type).length;
          const active = filter === type;
          return (
            <button
              key={type}
              type="button"
              aria-pressed={active}
              onClick={() => setFilter(type)}
              className={`rounded-full border px-3 py-1 text-xs capitalize transition-colors ${
                active
                  ? "border-teal-400/60 bg-teal-500/10 text-teal-300"
                  : "border-slate-700 text-slate-400 hover:border-slate-500 hover:text-slate-200"
              }`}
            >
              {type} · {count}
            </button>
          );
        })}
      </div>

      {visible.length === 0 ? (
        <div className="mt-6 rounded-xl border border-dashed border-slate-700 bg-slate-900/30 p-6 text-sm leading-relaxed text-slate-500">
          {events.length === 0
            ? "Nothing has happened yet. Open the Simulator and crash a node, or run a scenario from the Scenario Lab — the events will appear here as the backend emits them."
            : `No events of type "${filter}" yet.`}
        </div>
      ) : (
        <ol className="relative mt-6 space-y-4 border-l border-slate-800 pl-6">
          {visible.map((event) => {
            const Icon = EVENT_ICONS[event.type];
            return (
              <li key={event.id} className="relative">
                <span className="absolute -left-[34px] top-1 flex size-5 items-center justify-center rounded-full border border-slate-700 bg-slate-950">
                  <Icon className={`size-3 ${EVENT_TONES[event.type]}`} aria-hidden />
                </span>
                <div className="rounded-lg border border-slate-800/70 bg-slate-900/40 p-3 transition-colors hover:bg-slate-900/70">
                  <p className="text-sm leading-snug text-slate-200">{event.description}</p>
                  <p className="mt-1 font-mono text-[11px] uppercase tracking-wide text-slate-500">
                    {event.type} · {formatTime(event.timestamp)}
                  </p>
                </div>
              </li>
            );
          })}
        </ol>
      )}

      <section className="mt-10">
        <h3 className="mb-3 text-sm font-semibold uppercase tracking-wider text-slate-400">
          Recent messages
        </h3>
        <MessagesPanel messages={state.recent_messages} />
      </section>
    </div>
  );
}
